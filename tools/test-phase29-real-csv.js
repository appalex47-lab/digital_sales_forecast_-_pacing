const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const fixture=JSON.parse(fs.readFileSync(path.join(root,'tools/phase30-real-fixture.json'),'utf8'));
const ctx=vm.createContext({FP:{},console});vm.runInContext(fs.readFileSync(path.join(root,'js/analytics/trendForecastEngine.js'),'utf8'),ctx);
const FE=ctx.FP.trendForecastEngine;const r=FE.analyzeMany(fixture.rows,{horizon:3,method:'ensemble',periodType:'month'});
let pass=0,fail=0;const t=(n,fn)=>{try{assert.ok(fn());console.log('PASS',n);pass++;}catch(e){console.log('FAIL',n,e.message);fail++;}};
t('Fixture proviene del CSV real',()=>fixture.source==='Venta Productos 2026.csv');
t('CSV real genera proyecciones',()=>r.status==='available'&&r.rows.length>2000);
t('Ranking prioriza confianza',()=>r.rows.every((x,i)=>i===0||x.confidenceScore<=r.rows[i-1].confidenceScore));
t('Hay confianza alta o media',()=>r.highConfidence+r.mediumConfidence>0);
t('Hay crecimiento y/o caída',()=>r.growth+r.decline>0);
t('Hay piezas históricas',()=>r.rows.filter(x=>Number.isFinite(x.latestUnits)).length>1000);
t('Hay backtesting',()=>r.rows.filter(x=>x.backtest&&x.backtest.periodsTested>0).length>1000);
t('Dirección humana',()=>r.rows.some(x=>typeof x.directionReading==='string'&&x.directionReading.length>10));
console.log(`RESULT ${pass}/${pass+fail} | entidades=${r.rows.length} | alta=${r.highConfidence} media=${r.mediumConfidence} baja=${r.lowConfidence} crecimiento=${r.growth} caída=${r.decline}`);process.exitCode=fail?1:0;
