const fs=require('fs');
const trend=fs.readFileSync('js/ui/trend-view.js','utf8');
const app=fs.readFileSync('js/app.js','utf8');
const css=fs.readFileSync('css/styles.css','utf8');
const checks=[];
const t=(name,ok)=>checks.push({name,ok});
t('Patrones avanzados explica por dónde empezar', /Empieza aquí/.test(trend) && /Prioriza/.test(trend));
t('Patrones avanzados mantiene positivos y negativos juntos pero ordenados por score', /Positivos y negativos permanecen juntos/.test(trend) && /sort\(\(x, y\) => \(y\.score/.test(trend));
t('La tabla tiene acción Leer', /data-action="an-select"/.test(trend));
t('Lectura de entidad vive dentro de Patrones avanzados', /advanced-reading/.test(trend) && !/id="an-selected-detail"/.test(trend));
t('La lectura tiene siguiente paso', /Siguiente paso/.test(trend) && /nextStep\(r\)/.test(trend));
t('La gráfica usa crecimiento y fecha/período', /Crecimiento por período/.test(trend) && /Fecha \/ período/.test(trend) && /trend-chart__zero/.test(trend));
t('Existe cierre de lectura', /an-clear-selection/.test(app));
t('UX responsive de la nueva lectura', /advanced-start/.test(css) && /entity-growth-chart/.test(css) && /@media\(max-width:760px\)/.test(css));
t('No se modificó el motor de patrones para esta corrección', !fs.readFileSync('js/analytics/patternEngine.js','utf8').includes('Correction 13'));
const pass=checks.filter(x=>x.ok).length;
console.log(`${pass}/${checks.length} checks UX/UI de Patrones Avanzados`);
checks.forEach(x=>console.log(`${x.ok?'PASS':'FAIL'} ${x.name}`));
if(pass!==checks.length) process.exit(1);
