p=E.reconcile(rows,[al[0]],'2026-10-14','2026-10-14','2026-10-14T08:00:00Z');
t('resuelta cuando deja de saltar',p.patches.some(x=>x.alert_key==='missing_actual|b'&&x.fields.status==='resolved'));
rows=E.applyTo(rows,p);
p=E.reconcile(rows,[al[0]],'2026-10-14','2026-10-12');
t('datos más viejos no resuelven ni actualizan nada',p.patches.length===0&&p.inserts.length===0);
p=E.reconcile(rows,[],'2026-10-14',null);
t('sin datos no resuelve nada',p.patches.length===0);
rows=E.applyTo(rows,E.reconcile(rows,al,'2026-10-15','2026-10-15'));
const rb=rows.find(r=>r.alert_key==='missing_actual|b');
