t('frase sobre cierre proyectado',c2.headline[0].includes('bajó'));
t('sin run no inventa',E.compare({},{}).status==='no_run'&&E.compare({channels:{},plan:{}},{}).status==='no_actual');
const wk=E.compare(run,{mode:'semana'});t('modo semana suma desde el lunes',wk.total.actual===140);
