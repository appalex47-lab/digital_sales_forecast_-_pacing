t('ciclo: nueva/sigue/resuelta',E.lifecycle({status:'open',first_seen:'2026-10-14'},'2026-10-14','2026-10-13').id==='new'&&E.lifecycle({status:'open',first_seen:'2026-10-10'},'2026-10-14','2026-10-13').days===5&&E.lifecycle({status:'resolved'},'2026-10-14','2026-10-13').id==='resolved');
